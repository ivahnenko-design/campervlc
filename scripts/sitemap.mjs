#!/usr/bin/env node
// Builds public/sitemap.xml from the site's own data: every route and guide in
// all 7 languages (Spanish at the plain URL, the others at ?lang=xx), each with
// the full hreflang set. Pages closed with noindex are left out.
//   node scripts/sitemap.mjs          write public/sitemap.xml (lastmod from git)
//   node scripts/sitemap.mjs --check  fail when the file lacks or has extra URLs
//                                     (prebuild; Vercel builds have no git history)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://campervlc.com";
const LANGS = ["es", "en", "de", "it", "nl", "ru", "uk"];
const OUT = join(root, "public/sitemap.xml");

const { ROUTE_PAGES } = await import(join(root, "src/data/routes-content.ts"));
const guides = JSON.parse(readFileSync(join(root, "content/guides/es.json"), "utf8")).guides;

// Path, source files whose last commit is the page's lastmod, priority.
const PAGES = [
  { path: "/", sources: ["src/i18n/translations", "src/components"], priority: "1.0", freq: "weekly" },
  ...ROUTE_PAGES.map((r) => ({ path: `/rutas/${r.slug}`, sources: ["src/data/routes-content.ts"], priority: "0.8", freq: "monthly" })),
  { path: "/guias", sources: ["content/guides"], priority: "0.7", freq: "monthly" },
  ...Object.keys(guides).map((slug) => ({ path: `/guias/${slug}`, sources: ["content/guides"], priority: "0.8", freq: "monthly" })),
  { path: "/condiciones", sources: ["content"], priority: "0.4", freq: "monthly" },
];

const url = (path, lang) => `${SITE}${path}${lang === "es" ? "" : `?lang=${lang}`}`;

function lastmod(sources) {
  try {
    const out = execFileSync("git", ["log", "-1", "--format=%cs", "--", ...sources], { cwd: root, encoding: "utf8" }).trim();
    if (out) return out;
  } catch {
    // no git: today
  }
  return new Date().toISOString().slice(0, 10);
}

function build() {
  const entries = [];
  for (const page of PAGES) {
    const mod = lastmod(page.sources);
    const alternates = [
      ...LANGS.map((l) => `    <xhtml:link rel="alternate" hreflang="${l}" href="${url(page.path, l)}"/>`),
      `    <xhtml:link rel="alternate" hreflang="x-default" href="${url(page.path, "es")}"/>`,
    ].join("\n");
    for (const lang of LANGS) {
      entries.push(
        `  <url>\n    <loc>${url(page.path, lang)}</loc>\n    <lastmod>${mod}</lastmod>\n` +
          `    <changefreq>${page.freq}</changefreq>\n    <priority>${page.priority}</priority>\n${alternates}\n  </url>`,
      );
    }
  }
  return (
    `<?xml version="1.0" encoding="UTF-8"?>\n` +
    `<!-- Generated by scripts/sitemap.mjs — do not edit by hand. -->\n` +
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"\n        xmlns:xhtml="http://www.w3.org/1999/xhtml">\n` +
    `${entries.join("\n")}\n</urlset>\n`
  );
}

const locs = (xml) => [...xml.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]).sort();

if (process.argv.includes("--check")) {
  const want = locs(build());
  const have = locs(readFileSync(OUT, "utf8"));
  const missing = want.filter((u) => !have.includes(u));
  const extra = have.filter((u) => !want.includes(u));
  if (missing.length || extra.length) {
    console.error("public/sitemap.xml is out of date. Run: node scripts/sitemap.mjs");
    if (missing.length) console.error("  missing:", missing.join(" "));
    if (extra.length) console.error("  extra:", extra.join(" "));
    process.exit(1);
  }
  console.log(`sitemap ok (${want.length} URLs)`);
} else {
  const xml = build();
  writeFileSync(OUT, xml);
  console.log(`public/sitemap.xml: ${locs(xml).length} URLs`);
}
